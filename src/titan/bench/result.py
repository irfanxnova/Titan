"""TitanBench benchmark result and status data models.

Defines structured, JSON-serializable benchmark execution results, pass/fail status,
and artifact tracking for reproducible failure-corpus runs.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any


class BenchmarkStatus(str, Enum):
    """Evaluation status of a benchmark execution against defined oracle expectations."""

    PASS = "PASS"
    FAIL = "FAIL"
    INVALID = "INVALID"


@dataclass(frozen=True)
class BenchmarkArtifacts:
    """Canonical artifact file paths generated by a benchmark scenario execution."""

    scenario_path: str | None = None
    trace_path: str | None = None
    replay_path: str | None = None
    analysis_path: str | None = None
    result_path: str | None = None

    def to_dict(self) -> dict[str, str | None]:
        """Serialize artifact paths to dictionary."""
        return {
            "scenario": self.scenario_path,
            "trace": self.trace_path,
            "replay": self.replay_path,
            "analysis": self.analysis_path,
            "result": self.result_path,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> BenchmarkArtifacts:
        """Construct BenchmarkArtifacts from dictionary."""
        return cls(
            scenario_path=data.get("scenario"),
            trace_path=data.get("trace"),
            replay_path=data.get("replay"),
            analysis_path=data.get("analysis"),
            result_path=data.get("result"),
        )


@dataclass(frozen=True)
class BenchmarkResult:
    """Authoritative outcome and telemetry of a completed TitanBench scenario run.

    Encapsulates runtime metrics, trace replay validity, root-cause failure analysis,
    and deterministic oracle evaluation.
    """

    scenario_id: str
    scenario_class: str
    status: BenchmarkStatus
    reason: str
    run_status: str
    replay_valid: bool
    replay_outcome: str
    root_failures_count: int
    recovery_status: str
    total_jobs: int
    completed_jobs: int
    failed_jobs: int
    total_attempts: int
    retries: int
    worker_failures: int
    worker_replacements: int
    duplicate_results_ignored: int
    execution_duration: float
    validation_errors: list[str] = field(default_factory=list)
    artifacts: BenchmarkArtifacts = field(default_factory=BenchmarkArtifacts)
    failure_analysis_summary: dict[str, Any] = field(default_factory=dict)
    metrics_summary: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        """Serialize benchmark result to a clean, JSON-compatible dictionary."""
        return {
            "scenario_id": self.scenario_id,
            "scenario_class": self.scenario_class,
            "status": self.status.value if isinstance(self.status, BenchmarkStatus) else str(self.status),
            "reason": self.reason,
            "run_status": self.run_status,
            "replay_valid": self.replay_valid,
            "replay_outcome": self.replay_outcome,
            "root_failures_count": self.root_failures_count,
            "recovery_status": self.recovery_status,
            "jobs": {
                "total": self.total_jobs,
                "completed": self.completed_jobs,
                "failed": self.failed_jobs,
            },
            "attempts": self.total_attempts,
            "retries": self.retries,
            "worker_failures": self.worker_failures,
            "worker_replacements": self.worker_replacements,
            "duplicate_results_ignored": self.duplicate_results_ignored,
            "execution_duration_sec": round(self.execution_duration, 4),
            "validation_errors": list(self.validation_errors),
            "artifacts": self.artifacts.to_dict(),
            "failure_analysis_summary": dict(self.failure_analysis_summary),
            "metrics_summary": dict(self.metrics_summary),
        }

    def to_json(self, indent: int | None = 2) -> str:
        """Serialize benchmark result to formatted JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> BenchmarkResult:
        """Construct BenchmarkResult from dictionary representation."""
        status_val = data["status"]
        status = (
            BenchmarkStatus(status_val)
            if status_val in BenchmarkStatus._value2member_map_
            else BenchmarkStatus[status_val]
        )
        jobs_data = data.get("jobs", {})
        artifacts_data = data.get("artifacts", {})
        return cls(
            scenario_id=data["scenario_id"],
            scenario_class=data["scenario_class"],
            status=status,
            reason=data.get("reason", ""),
            run_status=data.get("run_status", "UNKNOWN"),
            replay_valid=bool(data.get("replay_valid", False)),
            replay_outcome=data.get("replay_outcome", "UNKNOWN"),
            root_failures_count=int(data.get("root_failures_count", 0)),
            recovery_status=data.get("recovery_status", "UNKNOWN"),
            total_jobs=int(jobs_data.get("total", data.get("total_jobs", 0))),
            completed_jobs=int(jobs_data.get("completed", data.get("completed_jobs", 0))),
            failed_jobs=int(jobs_data.get("failed", data.get("failed_jobs", 0))),
            total_attempts=int(data.get("attempts", data.get("total_attempts", 0))),
            retries=int(data.get("retries", 0)),
            worker_failures=int(data.get("worker_failures", 0)),
            worker_replacements=int(data.get("worker_replacements", 0)),
            duplicate_results_ignored=int(data.get("duplicate_results_ignored", 0)),
            execution_duration=float(data.get("execution_duration_sec", data.get("execution_duration", 0.0))),
            validation_errors=list(data.get("validation_errors", [])),
            artifacts=BenchmarkArtifacts.from_dict(artifacts_data),
            failure_analysis_summary=dict(data.get("failure_analysis_summary", {})),
            metrics_summary=dict(data.get("metrics_summary", {})),
        )


@dataclass(frozen=True)
class BenchmarkSummary:
    """Aggregate summary of multiple benchmark scenario runs (e.g. run-all)."""

    total_scenarios: int
    passed: int
    failed: int
    invalid: int
    total_duration_sec: float
    results: list[BenchmarkResult] = field(default_factory=list)

    @property
    def all_passed(self) -> bool:
        """True if every executed scenario passed its oracle."""
        return self.passed == self.total_scenarios and self.total_scenarios > 0

    def to_dict(self) -> dict[str, Any]:
        """Serialize benchmark summary to dictionary."""
        return {
            "total_scenarios": self.total_scenarios,
            "passed": self.passed,
            "failed": self.failed,
            "invalid": self.invalid,
            "all_passed": self.all_passed,
            "total_duration_sec": round(self.total_duration_sec, 4),
            "results": [r.to_dict() for r in self.results],
        }

    def to_json(self, indent: int | None = 2) -> str:
        """Serialize benchmark summary to formatted JSON string."""
        return json.dumps(self.to_dict(), indent=indent)
